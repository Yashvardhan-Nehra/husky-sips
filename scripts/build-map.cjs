// Usage: node build-map.cjs <input.geojson> <output.ts>
// Simplifies a (Multi)Polygon GeoJSON with Douglas-Peucker, projects with Web Mercator into a
// 0..1000 x 0..1100 viewBox, and writes a TypeScript module with path data + projection params.
const fs = require("fs");
const [,, input, output] = process.argv;
const g = JSON.parse(fs.readFileSync(input, "utf8"));

const TOL_DEG = 0.02;          // simplification tolerance in degrees (~2 km)
const MIN_RING_PTS = 6;        // drop tiny islands after simplification
const MIN_RING_AREA = 0.0008;  // deg^2 — drop specks

function dp(points, tol) {
  if (points.length < 3) return points;
  const sqTol = tol * tol;
  const keep = new Uint8Array(points.length);
  keep[0] = 1; keep[points.length - 1] = 1;
  const stack = [[0, points.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    let maxD = 0, idx = -1;
    const [ax, ay] = points[a], [bx, by] = points[b];
    const dx = bx - ax, dy = by - ay;
    const len2 = dx * dx + dy * dy;
    for (let i = a + 1; i < b; i++) {
      const [px, py] = points[i];
      let d;
      if (len2 === 0) d = (px - ax) ** 2 + (py - ay) ** 2;
      else {
        let t = ((px - ax) * dx + (py - ay) * dy) / len2;
        t = Math.max(0, Math.min(1, t));
        d = (px - (ax + t * dx)) ** 2 + (py - (ay + t * dy)) ** 2;
      }
      if (d > maxD) { maxD = d; idx = i; }
    }
    if (maxD > sqTol && idx > 0) { keep[idx] = 1; stack.push([a, idx], [idx, b]); }
  }
  return points.filter((_, i) => keep[i]);
}
function ringArea(r) {
  let a = 0;
  for (let i = 0; i < r.length - 1; i++) a += r[i][0] * r[i + 1][1] - r[i + 1][0] * r[i][1];
  return Math.abs(a / 2);
}

const polys = [];
for (const f of g.features) {
  const t = f.geometry.type;
  const list = t === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates;
  for (const p of list) {
    const rings = [];
    for (let ri = 0; ri < p.length; ri++) {
      const r = p[ri];
      if (ringArea(r) < MIN_RING_AREA && ri === 0) { rings.length = 0; break; }
      const s = dp(r, TOL_DEG);
      if (s.length >= MIN_RING_PTS) rings.push(s);
    }
    if (rings.length) polys.push(rings);
  }
}

// bounds
let minLon = Infinity, maxLon = -Infinity, minLat = Infinity, maxLat = -Infinity;
for (const p of polys) for (const r of p) for (const [lon, lat] of r) {
  if (lon < minLon) minLon = lon; if (lon > maxLon) maxLon = lon;
  if (lat < minLat) minLat = lat; if (lat > maxLat) maxLat = lat;
}
const mercY = (lat) => Math.log(Math.tan(Math.PI / 4 + (lat * Math.PI / 180) / 2));
const W = 1000, PAD = 20;
const yTop = mercY(maxLat), yBot = mercY(minLat);
const scale = (W - 2 * PAD) / (maxLon - minLon);
const H = Math.round((yTop - yBot) * scale * (180 / Math.PI) * (Math.PI / 180) + 2 * PAD);
// Note: mercY is unitless (radians-ish); lon scale is per degree. Make both consistent in degrees:
const sx = (W - 2 * PAD) / (maxLon - minLon);
const sy = sx * (180 / Math.PI); // mercator y is in radians-equivalent units; convert to "degrees" scale
const Hreal = Math.round((yTop - yBot) * sy + 2 * PAD);
function project(lon, lat) {
  const x = PAD + (lon - minLon) * sx;
  const y = PAD + (yTop - mercY(lat)) * sy;
  return [Math.round(x * 10) / 10, Math.round(y * 10) / 10];
}
let d = "";
let totalPts = 0;
for (const p of polys) for (const r of p) {
  const pts = r.map(([lon, lat]) => project(lon, lat));
  totalPts += pts.length;
  d += "M" + pts[0][0] + " " + pts[0][1];
  for (let i = 1; i < pts.length; i++) d += "L" + pts[i][0] + " " + pts[i][1];
  d += "Z";
}
const ts = `// AUTO-GENERATED by scripts/build-map.cjs — do not edit by hand.
// Source: "India boundaries" by DataMeet India community, Country/india-soi.geojson
// (Survey of India state map), licensed CC BY 4.0 — https://github.com/datameet/maps
// Simplification tolerance: ${TOL_DEG}° · rings kept: ${polys.length} · points: ${totalPts}
export const INDIA_VIEWBOX = { width: ${W}, height: ${Hreal} } as const;
export const INDIA_PROJECTION = {
  minLon: ${minLon}, maxLon: ${maxLon}, minLat: ${minLat}, maxLat: ${maxLat},
  pad: ${PAD}, sx: ${sx}, sy: ${sy}, yTop: ${yTop},
} as const;
export const INDIA_OUTLINE_PATH = ${JSON.stringify(d)};
`;
fs.writeFileSync(output, ts);
console.log({ polys: polys.length, totalPts, W, H: Hreal, minLon, maxLon, minLat, maxLat, bytes: ts.length });
